// Copies the shared spec (../spec or SPEC_DIR) into spec/ and writes
// src/spec.js so the tool contract loads with no JSON import support.
import { cpSync, readFileSync, writeFileSync, rmSync, lstatSync } from "node:fs";
const from = process.env.SPEC_DIR || new URL("../../spec/", import.meta.url).pathname;
const to = new URL("../spec/", import.meta.url).pathname;
try { if (lstatSync(to.replace(/\/$/, "")).isSymbolicLink()) rmSync(to.replace(/\/$/, "")); } catch {}
cpSync(from, to, { recursive: true, filter: (p) => !p.includes("/.git") });
const tools = JSON.parse(readFileSync(to + "tools.json", "utf8"));
writeFileSync(new URL("../src/spec.js", import.meta.url), `// Generated by scripts/sync-spec.mjs from spec/tools.json. Do not edit.\nexport const SPEC = ${JSON.stringify(tools, null, 2)};\n`);
console.log(`spec ${tools.version}: ${tools.tools.length} tools`);
